/* MOTION LAB — VIDEO INTERACTIONS */

document.querySelectorAll('.motion-media').forEach(media => {
    const video = media.querySelector('video');
    const button = media.querySelector('.motion-play');

    if (!video || !button) return;

    // Silent preview on desktop hover
    media.addEventListener('mouseenter', () => {
        if (video.controls) return;
        video.muted = true;
        video.play().catch(() => {});
    });

    media.addEventListener('mouseleave', () => {
        if (video.controls) return;
        video.pause();
        video.currentTime = 0;
    });

    // Click to watch with sound and controls
    button.addEventListener('click', () => {
        video.controls = true;
        video.muted = false;
        video.loop = false;
        video.play().catch(() => {});
        button.hidden = true;
    });
});

