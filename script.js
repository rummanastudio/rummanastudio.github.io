/* RUMMANA V3 — Selected Work Carousel */

const workSlider = document.getElementById('workSlider');
const workPrev = document.getElementById('workPrev');
const workNext = document.getElementById('workNext');
const workCounter = document.getElementById('workCounter');

if (workSlider && workPrev && workNext && workCounter) {
    const cards = [...workSlider.querySelectorAll('.work-card')];

    function currentWorkIndex() {
        const center = workSlider.scrollLeft + workSlider.clientWidth / 2;

        let nearest = 0;
        let minDistance = Infinity;

        cards.forEach((card, index) => {
            const cardCenter = card.offsetLeft - workSlider.offsetLeft
                + card.offsetWidth / 2;
            const distance = Math.abs(center - cardCenter);

            if (distance < minDistance) {
                minDistance = distance;
                nearest = index;
            }
        });

        return nearest;
    }

    function updateWorkControls() {
        const index = currentWorkIndex();

        workCounter.textContent =
            String(index + 1).padStart(2, '0') +
            ' / ' +
            String(cards.length).padStart(2, '0');

        workPrev.disabled = index === 0;
        workNext.disabled = index === cards.length - 1;
    }

    function goToWork(index) {
        const target = cards[Math.max(0, Math.min(index, cards.length - 1))];
        if (!target) return;

        const left = target.offsetLeft - workSlider.offsetLeft
            - (workSlider.clientWidth - target.offsetWidth) / 2;

        workSlider.scrollTo({
            left,
            behavior: window.matchMedia('(prefers-reduced-motion: reduce)').matches
                ? 'instant'
                : 'smooth'
        });
    }

    workPrev.addEventListener('click', () => {
        goToWork(currentWorkIndex() - 1);
    });

    workNext.addEventListener('click', () => {
        goToWork(currentWorkIndex() + 1);
    });

    let isDragging = false;
    let startX = 0;
    let startScroll = 0;

    workSlider.addEventListener('pointerdown', e => {
        if (e.pointerType !== 'mouse' || e.button !== 0) return;

        isDragging = true;
        startX = e.clientX;
        startScroll = workSlider.scrollLeft;
        workSlider.classList.add('dragging');
    });

    window.addEventListener('pointermove', e => {
        if (!isDragging) return;
        workSlider.scrollLeft = startScroll - (e.clientX - startX);
    });

    window.addEventListener('pointerup', () => {
        if (!isDragging) return;
        isDragging = false;
        workSlider.classList.remove('dragging');
        updateWorkControls();
    });

    workSlider.addEventListener('scroll', updateWorkControls, {
        passive: true
    });

    window.addEventListener('resize', updateWorkControls);

    updateWorkControls();
}


